export const doctorService = {
  getAllDoctors: (): Doctor[] => {
    return INITIAL_DOCTORS;
  },

  getDoctorById: (id: string): Doctor | undefined => {
    return INITIAL_DOCTORS.find((d) => d.id === id);
  },

  filterDoctors: (params: { specialty?: string; search?: string }): Doctor[] => {
    let result = INITIAL_DOCTORS;
    if (params.specialty && params.specialty !== 'All') {
      result = result.filter(
        (doc) => doc.specialty.toLowerCase() === params.specialty?.toLowerCase()
      );
    }
    if (params.search && params.search.trim() !== '') {
      const term = params.search.toLowerCase();
      result = result.filter(
        (doc) =>
          doc.name.toLowerCase().includes(term) ||
          doc.specialty.toLowerCase().includes(term) ||
          doc.department.toLowerCase().includes(term) ||
          doc.about.toLowerCase().includes(term)
      );
    }
    return result;
  },

  getSpecialties: (): Specialty[] => {
    return SPECIALTIES;
  },
};
